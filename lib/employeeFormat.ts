/** Input helpers for the employee profile form. Pure functions, so they can be
 * tested without the UI. */

/** Keeps digits only, formats as (XXX) XXX-XXXX while typing. */
export function formatPhone(input: string): string {
  const digits = input.replace(/\D/g, "").slice(0, 10);
  if (digits.length === 0) return "";
  if (digits.length < 4) return `(${digits}`;
  if (digits.length < 7) return `(${digits.slice(0, 3)}) ${digits.slice(3)}`;
  return `(${digits.slice(0, 3)}) ${digits.slice(3, 6)}-${digits.slice(6)}`;
}

/** Formats an SSN as XXX-XX-XXXX while typing. Shown masked on screen
 * afterwards; only the last four are kept (see ssnLast4). */
export function formatSsn(input: string): string {
  const digits = input.replace(/\D/g, "").slice(0, 9);
  if (digits.length < 4) return digits;
  if (digits.length < 6) return `${digits.slice(0, 3)}-${digits.slice(3)}`;
  return `${digits.slice(0, 3)}-${digits.slice(3, 5)}-${digits.slice(5)}`;
}

/** The last four digits of a full SSN, or null when the input is not a
 * complete 9-digit number. The full number never leaves the form. */
export function ssnLast4(input: string): string | null {
  const digits = input.replace(/\D/g, "");
  return digits.length === 9 ? digits.slice(-4) : null;
}

/** Digits only, up to 5 (US ZIP). */
export function formatZip(input: string): string {
  return input.replace(/\D/g, "").slice(0, 5);
}

/** Uppercase two-letter state code, letters only. */
export function formatState(input: string): string {
  return input.replace(/[^a-zA-Z]/g, "").slice(0, 2).toUpperCase();
}

